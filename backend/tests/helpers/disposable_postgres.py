"""Offline destination guard for disposable native PostgreSQL test fixtures."""
import os
from collections.abc import Mapping
from urllib.parse import parse_qsl, quote, unquote, urlsplit

from psycopg.conninfo import conninfo_to_dict

ERROR = ('A disposable PostgreSQL URI with an explicit numeric loopback host, port and '
         'database is required; routing overrides and ambient PostgreSQL routing settings are refused.')
ROUTING_ENV = ('PGHOST', 'PGHOSTADDR', 'PGPORT', 'PGDATABASE', 'PGSERVICE', 'PGSERVICEFILE')
ROUTING_QUERY = frozenset(('host', 'hostaddr', 'port', 'dbname', 'service', 'servicefile'))


def validate_disposable_postgres_dsn(dsn: str, environ: Mapping[str, str] | None = None) -> None:
    """Validate libpq's effective destination without connecting or exposing credentials."""
    environ = os.environ if environ is None else environ
    try:
        if any(environ.get(key) for key in ROUTING_ENV):
            raise ValueError
        if not dsn or any(character.isspace() or ord(character) < 32 for character in dsn):
            raise ValueError
        uri = urlsplit(dsn)
        if (uri.scheme not in ('postgres', 'postgresql') or uri.hostname not in ('127.0.0.1', '::1')
                or uri.port is None or not 1 <= uri.port <= 65535 or uri.fragment
                or not uri.path.startswith('/') or not uri.path[1:]):
            raise ValueError
        if any(key in ROUTING_QUERY for key, _ in parse_qsl(uri.query, keep_blank_values=True)):
            raise ValueError
        effective = conninfo_to_dict(dsn)
        if (effective.get('host') != uri.hostname or effective.get('port') != str(uri.port)
                or effective.get('dbname') != unquote(uri.path[1:])
                or 'hostaddr' in effective or 'service' in effective):
            raise ValueError
    except Exception:
        # libpq parse errors may include URI/password/query text. Never surface them.
        raise ValueError(ERROR) from None


def validate_disposable_postgres_config(config: object, environ: Mapping[str, str] | None = None) -> None:
    """Validate the exact kwargs shape generated by subscription.postgres.mjs."""
    try:
        if not isinstance(config, dict) or set(config) != {'host', 'port', 'dbname', 'user', 'password'}:
            raise ValueError
        if any(not isinstance(config[key], str) for key in ('host', 'dbname', 'user', 'password')):
            raise ValueError
        if config['host'] not in ('127.0.0.1', '::1') or type(config['port']) is not int or not config['user']:
            raise ValueError
        host = '[' + config['host'] + ']' if config['host'] == '::1' else config['host']
        dsn = ('postgresql://' + quote(config['user'], safe='') + ':' + quote(config['password'], safe='')
               + '@' + host + ':' + str(config['port']) + '/' + quote(config['dbname'], safe=''))
        validate_disposable_postgres_dsn(dsn, environ)
    except Exception:
        raise ValueError(ERROR) from None
